// Tests of the payload generator (payloads.mjs): the real tree's check, the shape of the output, and fixtures for
// each way a payload class can be refused. Run with: node --test web/scripts/
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { after, describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const script = join(here, 'payloads.mjs');
const repoRoot = resolve(here, '..', '..');
const liveDir = join(repoRoot, 'src/ocutalon/cls/OcuTalon/Live');
const realOut = join(repoRoot, 'web/src/app/live/payloads.ts');

const work = mkdtempSync(join(tmpdir(), 'ocutalon-payloads-'));
after(() => rmSync(work, { recursive: true, force: true }));

const run = (...args) => spawnSync(process.execPath, [script, ...args], { encoding: 'utf8' });

const classText = (name, properties) =>
  `/// A fixture.\nClass OcuTalon.Live.Payload.${name} Extends (%RegisteredObject, %JSON.Adaptor)\n{\n\n${properties.join('\n\n')}\n\n}\n`;

const ALPHA = [
  'Property Ref As %String(%JSONFIELDNAME = "ref", MAXLEN = 22);',
  'Property Count As %Integer(%JSONFIELDNAME = "count");',
  'Property Price As %Numeric(%JSONFIELDNAME = "price", SCALE = 2);',
  'Property Done As %Boolean(%JSONFIELDNAME = "done") [ InitialExpression = 0 ];',
  'Property Tags As list Of %String(%JSONFIELDNAME = "tags");',
  'Property Thing As OcuTalon.Live.Payload.Part.Thing(%JSONFIELDNAME = "thing");',
  'Property Things As list Of OcuTalon.Live.Payload.Part.Thing(%JSONFIELDNAME = "things");',
  'Property Peer As OcuTalon.Live.Payload.Beta(%JSONFIELDNAME = "peer");',
];

/** A fixture tree: Publish.cls, Payload/Alpha.cls (with `alpha`'s properties), Payload/Beta.cls, Payload/Part/Thing.cls. */
function fixture(name, { alpha = ALPHA, types = 'alpha:Alpha,beta:Beta', extra = {} } = {}) {
  const dir = join(work, name);
  mkdirSync(join(dir, 'Payload/Part'), { recursive: true });
  writeFileSync(join(dir, 'Publish.cls'), `Class OcuTalon.Live.Publish\n{\n\nParameter TYPES = "${types}";\n\n}\n`);
  writeFileSync(join(dir, 'Payload/Alpha.cls'), classText('Alpha', alpha));
  writeFileSync(join(dir, 'Payload/Beta.cls'), classText('Beta', ['Property Text As %String(%JSONFIELDNAME = "text", MAXLEN = "");']));
  writeFileSync(join(dir, 'Payload/Part/Thing.cls'), classText('Part.Thing', ['Property Name As %String(%JSONFIELDNAME = "name", MAXLEN = 128);']));
  for (const [file, text] of Object.entries(extra)) {
    mkdirSync(dirname(join(dir, file)), { recursive: true });
    writeFileSync(join(dir, file), text);
  }
  return dir;
}

const args = (dir, ...extra) => ['--publish', join(dir, 'Publish.cls'), '--payload-dir', join(dir, 'Payload'), '--out', join(dir, 'payloads.ts'), ...extra];

describe('the real tree', () => {
  it('has a current payloads.ts', () => {
    const r = run('--check');
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stdout, /payloads: generated files are current/);
  });

  it('holds an interface for each of the 16 events, Decision included, and the closed lists', () => {
    const text = readFileSync(realOut, 'utf8');
    assert.match(text.split('\n')[0], /^\/\/ Generated by web\/scripts\/payloads\.mjs/);
    assert.ok(!/[^\x20-\x7e\n]/.test(text), 'ASCII only');
    const types = [
      ['chat.message', 'ChatMessage'], ['notification', 'Notification'], ['phone', 'Phone'], ['mailbox', 'Mailbox'],
      ['decision', 'Decision'], ['approval', 'Approval'], ['turn.step', 'TurnStep'], ['reminder', 'Reminder'],
      ['pairing', 'Pairing'], ['status', 'Status'], ['reset', 'Reset'], ['breakfeed.progress', 'BreakFeedProgress'],
      ['guide.state', 'GuideState'], ['incident', 'Incident'], ['watch.progress', 'WatchProgress'], ['check', 'Check'],
    ];
    for (const [type, cls] of types) {
      assert.match(text, new RegExp(`export interface ${cls}Payload \\{`), `${cls}Payload`);
      assert.match(text, new RegExp(`^  '${type.replace('.', '\\.')}': ${cls}Payload;$`, 'm'), `LivePayloads maps ${type}`);
      assert.match(text, new RegExp(`^  \\| '${type.replace('.', '\\.')}';?$`, 'm'), `LiveEventType holds ${type}`);
    }
    for (const part of ['DryRun', 'IncidentEvidence', 'IncidentEvidenceItem', 'IncidentGroup', 'IncidentRequest', 'IncidentRequestResult', 'IncidentTraceTargets', 'ItemNoun', 'StatusSlots', 'TraceTarget']) {
      assert.match(text, new RegExp(`export interface ${part} \\{`), part);
    }
    assert.match(text, /^export interface IncidentPayload \{[\s\S]*?\n  itemNoun\?: ItemNoun;[\s\S]*?\n  groups\?: IncidentGroup\[\];[\s\S]*?\n  traceTargets\?: IncidentTraceTargets;/m);
    assert.match(text, /^export interface DecisionPayload \{[\s\S]*?\n  costUSD\?: number;/m);
    assert.match(text, /^export interface IncidentPayload \{[\s\S]*?\n  fallback\?: boolean;/m);
  });

  it('nests the decision payload, the cost and the check rows in ChatMessagePayload', () => {
    const text = readFileSync(realOut, 'utf8');
    assert.match(text, /^export interface ChatMessagePayload \{[\s\S]*?\n  decision\?: DecisionPayload;\n  turnCost\?: Cost;\n  checkKey\?: string;\n  checks\?: CheckRow\[\];\n  traceUrl\?: string;\n\}/m);
    assert.match(text, /^export interface Cost \{\n  inputTokens\?: number;[\s\S]*?\n  costUSD\?: number;\n\}/m);
    assert.match(text, /^export interface CheckRow \{\n  result\?: string;\n  entry\?: string;\n  finding\?: string;\n  checkedAt\?: string;\n\}/m);
    assert.match(text, /^export interface TurnStepPayload \{\n  turnRef\?: string;\n  decisionRef\?: string;/m);
  });
});

describe('traceUrl in the real tree', () => {
  /** The generated interfaces as { name, fields } in file order, each field as its key. */
  const interfaces = () =>
    [...readFileSync(realOut, 'utf8').matchAll(/^export interface (\w+) \{\n([\s\S]*?)\n\}/gm)].map((match) => ({
      name: match[1],
      fields: match[2].split('\n').map((line) => line.trim().replace(/\?:.*$/, '')),
    }));

  it('is on exactly the interfaces that have both traceHeaderId and traceNamespace, as their last field', () => {
    const traced = [];
    for (const { name, fields } of interfaces()) {
      const both = fields.includes('traceHeaderId') && fields.includes('traceNamespace');
      assert.equal(fields.includes('traceUrl'), both, `${name}: traceUrl is there exactly when both trace fields are`);
      if (both) {
        traced.push(name);
        assert.equal(fields.at(-1), 'traceUrl', `${name}: traceUrl is the last field`);
      }
    }
    assert.deepEqual(traced.sort(), ['ApprovalPayload', 'CheckPayload', 'ChatMessagePayload', 'DecisionPayload', 'ReminderPayload', 'TraceTarget'].sort());
    assert.ok(!traced.includes('NotificationPayload'), 'a notification carries its decision, not a target of its own');
  });

  it('types it as an optional string', () => {
    assert.match(readFileSync(realOut, 'utf8'), /^export interface CheckPayload \{[\s\S]*?\n  traceNamespace\?: string;\n  traceUrl\?: string;\n\}/m);
  });

  it('gives DecisionPayload the two item indexes before traceUrl', () => {
    assert.match(readFileSync(realOut, 'utf8'), /^export interface DecisionPayload \{[\s\S]*?\n  traceNamespace\?: string;\n  traceItemIndex\?: number;\n  traceItemIndexNoEvents\?: number;\n  traceUrl\?: string;\n\}/m);
  });
});

describe('a fixture tree', () => {
  it('adds traceUrl last to a class with both trace fields, and to no other', () => {
    const alpha = [...ALPHA, 'Property TraceHeaderId As %Integer(%JSONFIELDNAME = "traceHeaderId");', 'Property TraceNamespace As %String(%JSONFIELDNAME = "traceNamespace", MAXLEN = 128);'];
    const dir = fixture('trace-url', {
      alpha,
      extra: {
        'Payload/Beta.cls': classText('Beta', ['Property TraceHeaderId As %Integer(%JSONFIELDNAME = "traceHeaderId");']),
        'Payload/Part/Thing.cls': classText('Part.Thing', ['Property TraceHeaderId As %Integer(%JSONFIELDNAME = "traceHeaderId");', 'Property TraceNamespace As %String(%JSONFIELDNAME = "traceNamespace", MAXLEN = 128);']),
      },
    });
    assert.equal(run(...args(dir)).status, 0);
    const text = readFileSync(join(dir, 'payloads.ts'), 'utf8');
    assert.match(text, /export interface Thing \{\n  traceHeaderId\?: number;\n  traceNamespace\?: string;\n  traceUrl\?: string;\n\}/);
    assert.match(text, /export interface AlphaPayload \{[\s\S]*?\n  traceHeaderId\?: number;\n  traceNamespace\?: string;\n  traceUrl\?: string;\n\}/);
    assert.match(text, /export interface BetaPayload \{\n  traceHeaderId\?: number;\n\}/);
    assert.equal(text.match(/traceUrl\?: string;/g).length, 2);
  });

  it('maps each type, writes the file, and then finds it current', () => {
    const dir = fixture('maps');
    let r = run(...args(dir));
    assert.equal(r.status, 0, r.stderr);
    const text = readFileSync(join(dir, 'payloads.ts'), 'utf8');
    assert.equal(
      text,
      [
        '// Generated by web/scripts/payloads.mjs from the OcuTalon.Live.Payload classes. Do not edit; run: npm --prefix web run payloads',
        '',
        'export interface Thing {\n  name?: string;\n}',
        '',
        'export interface AlphaPayload {\n  ref?: string;\n  count?: number;\n  price?: number;\n  done?: boolean;\n  tags?: string[];\n  thing?: Thing;\n  things?: Thing[];\n  peer?: BetaPayload;\n}',
        '',
        'export interface BetaPayload {\n  text?: string;\n}',
        '',
        "export type LiveEventType =\n  | 'alpha'\n  | 'beta';",
        '',
        "export interface LivePayloads {\n  'alpha': AlphaPayload;\n  'beta': BetaPayload;\n}",
        '',
      ].join('\n'),
    );
    r = run(...args(dir, '--check'));
    assert.equal(r.status, 0, r.stderr);
  });

  it('finds the file stale after a class changes without regenerating', () => {
    const dir = fixture('stale');
    assert.equal(run(...args(dir)).status, 0);
    const renamed = ALPHA.map((line) => line.replace('Property Count As %Integer(%JSONFIELDNAME = "count")', 'Property Total As %Integer(%JSONFIELDNAME = "total")'));
    writeFileSync(join(dir, 'Payload/Alpha.cls'), classText('Alpha', renamed));
    const r = run(...args(dir, '--check'));
    assert.equal(r.status, 1);
    assert.match(r.stderr, /payloads\.ts is stale: run npm --prefix web run payloads/);
  });

  it('finds a missing file stale', () => {
    const dir = fixture('missing');
    const r = run(...args(dir, '--check'));
    assert.equal(r.status, 1);
    assert.match(r.stderr, /payloads\.ts is stale/);
  });
});

describe('refusals name the file and line', () => {
  const refuse = (name, options, pattern) => {
    const dir = fixture(name, options);
    const r = run(...args(dir));
    assert.equal(r.status, 1, `${name}: should exit 1: ${r.stderr}`);
    assert.match(r.stderr, pattern, `${name}: ${r.stderr}`);
  };
  const withLine = (line) => [ALPHA[0], line, ...ALPHA.slice(1)];

  it('a property with no %JSONFIELDNAME', () => {
    refuse('nojson', { alpha: withLine('Property Plain As %String(MAXLEN = 22);') }, /Payload\/Alpha\.cls:7: property Plain has no %JSONFIELDNAME/);
    refuse('noparams', { alpha: withLine('Property Bare As %String;') }, /Payload\/Alpha\.cls:7: property Bare has no %JSONFIELDNAME/);
  });

  it('a key that is not the property name with a lower-case first letter', () => {
    refuse('snake', { alpha: withLine('Property ItemNoun As %String(%JSONFIELDNAME = "item_noun", MAXLEN = 22);') }, /Payload\/Alpha\.cls:7: property ItemNoun has the JSON key 'item_noun', not .* \('itemNoun'\)/);
    refuse('pascal', { alpha: withLine('Property ItemNoun As %String(%JSONFIELDNAME = "ItemNoun", MAXLEN = 22);') }, /Payload\/Alpha\.cls:7: property ItemNoun has the JSON key 'ItemNoun'/);
    refuse('lower', { alpha: withLine('Property ItemNoun As %String(%JSONFIELDNAME = "itemnoun", MAXLEN = 22);') }, /Payload\/Alpha\.cls:7: property ItemNoun has the JSON key 'itemnoun'/);
    refuse('other', { alpha: withLine('Property Count2 As %Integer(%JSONFIELDNAME = "total");') }, /Payload\/Alpha\.cls:7: property Count2 has the JSON key 'total'/);
  });

  it('a type that is not mapped', () => {
    refuse('date', { alpha: withLine('Property When As %Date(%JSONFIELDNAME = "when");') }, /Payload\/Alpha\.cls:7: property When has the type %Date, which the generator does not map/);
    refuse('listint', { alpha: withLine('Property Counts As list Of %Integer(%JSONFIELDNAME = "counts");') }, /Payload\/Alpha\.cls:7: property Counts has the type list Of %Integer/);
    refuse('foreign', { alpha: withLine('Property Other As OcuTalon.Data.Session(%JSONFIELDNAME = "other");') }, /Payload\/Alpha\.cls:7: property Other has the type OcuTalon\.Data\.Session/);
    refuse('nodirect', { alpha: withLine('Property Gone As OcuTalon.Live.Payload.Gone(%JSONFIELDNAME = "gone");') }, /Payload\/Alpha\.cls:7: property Gone has the type OcuTalon\.Live\.Payload\.Gone/);
    refuse('nopart', { alpha: withLine('Property Gone As OcuTalon.Live.Payload.Part.Gone(%JSONFIELDNAME = "gone");') }, /Payload\/Alpha\.cls:7: property Gone has the type OcuTalon\.Live\.Payload\.Part\.Gone/);
  });

  it('a property that is indented or not written as Property', () => {
    refuse('indented', { alpha: withLine('  Property Indented As %String(%JSONFIELDNAME = "indented");') }, /Payload\/Alpha\.cls:7: cannot read this property/);
    refuse('lowercase', { alpha: withLine('property Lower As %String(%JSONFIELDNAME = "lower");') }, /Payload\/Alpha\.cls:7: cannot read this property/);
  });

  it('a property that is not on one line', () => {
    refuse('wrapped', { alpha: withLine('Property Wrapped As %String(%JSONFIELDNAME = "wrapped",') }, /Payload\/Alpha\.cls:7: cannot read this property/);
  });

  it('an event type with no class, and a class that is not an event type', () => {
    refuse('notype', { types: 'alpha:Alpha,beta:Beta,gamma:Gamma' }, /Publish\.cls:4: the type 'gamma' names OcuTalon\.Live\.Payload\.Gamma, which has no class file/);
    refuse('noevent', { types: 'alpha:Alpha' }, /Payload\/Beta\.cls: the class OcuTalon\.Live\.Payload\.Beta is not in the TYPES parameter/);
    refuse('badpair', { types: 'alpha:Alpha,beta' }, /Publish\.cls:4: TYPES holds 'beta'/);
  });

  it('a class whose name is not its path', () => {
    refuse('wrongname', { extra: { 'Payload/Gamma.cls': classText('Delta', []) }, types: 'alpha:Alpha,beta:Beta,gamma:Gamma' }, /Payload\/Gamma\.cls: the class is OcuTalon\.Live\.Payload\.Delta, but its path says OcuTalon\.Live\.Payload\.Gamma/);
  });
});

describe('the real classes, changed in a copy', () => {
  const copy = (name) => {
    const dir = join(work, name);
    mkdirSync(dir, { recursive: true });
    cpSync(join(liveDir, 'Payload'), join(dir, 'Payload'), { recursive: true });
    cpSync(join(liveDir, 'Publish.cls'), join(dir, 'Publish.cls'));
    cpSync(realOut, join(dir, 'payloads.ts'));
    return dir;
  };
  const edit = (dir, file, from, to) => {
    const path = join(dir, file);
    const text = readFileSync(path, 'utf8');
    assert.ok(text.includes(from), `${file} holds ${from}`);
    writeFileSync(path, text.replace(from, to));
  };

  it('the copy of the real tree is current', () => {
    const dir = copy('real-copy');
    const r = run(...args(dir, '--check'));
    assert.equal(r.status, 0, r.stderr);
  });

  it('Incident.ItemNoun with the key item_noun is refused', () => {
    const dir = copy('item-noun');
    edit(dir, 'Payload/Incident.cls', '%JSONFIELDNAME = "itemNoun"', '%JSONFIELDNAME = "item_noun"');
    const r = run(...args(dir));
    assert.equal(r.status, 1);
    assert.match(r.stderr, /Payload\/Incident\.cls:\d+: property ItemNoun has the JSON key 'item_noun'/);
  });

  it('Reminder.DueAt renamed without regenerating makes the check fail', () => {
    const dir = copy('due-at');
    edit(dir, 'Payload/Reminder.cls', 'Property DueAt As %String(%JSONFIELDNAME = "dueAt"', 'Property DueOn As %String(%JSONFIELDNAME = "dueOn"');
    const r = run(...args(dir, '--check'));
    assert.equal(r.status, 1);
    assert.match(r.stderr, /payloads\.ts is stale/);
  });
});
